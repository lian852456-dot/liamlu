import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const assets={css:fs.readFileSync(path.join(root,'readonly-dashboard.css'),'utf8'),core:fs.readFileSync(path.join(root,'readonly-dashboard-core.js'),'utf8')};
if(/@import|url\(\s*['"]?(?:https?:|\/\/)/i.test(assets.css))throw Error('Snapshot styles must not depend on external assets');
const output='// Generated by scripts/build-store-readonly-assets.mjs; public presentation code only.\n'+
 '(function(root){const assets='+JSON.stringify(assets)+';if(typeof module===\'object\'&&module.exports)module.exports=assets;else root.ReadonlyStoreExportAssets=assets;})(typeof globalThis!==\'undefined\'?globalThis:this);\n';
fs.writeFileSync(path.join(root,'readonly-store-export-assets.js'),output);
console.log('Updated standalone snapshot assets from the existing dashboard CSS and conversion core.');
