import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {buildTemplate,VERSION} from './export-price-offline.mjs';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const template=buildTemplate();
const assets={version:VERSION,sourceCommit:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),templateSha256:crypto.createHash('sha256').update(template).digest('hex'),template};
fs.writeFileSync(path.join(root,'gas/ThreecPriceOfflineCore.gs'),'// Generated from threec-price-offline-core.js; no price data or credentials.\n'+fs.readFileSync(path.join(root,'threec-price-offline-core.js'),'utf8'));
fs.writeFileSync(path.join(root,'gas/ThreecPriceOfflineAssets.gs'),'// Generated by scripts/build-price-offline-assets.mjs; presentation only.\nconst THREEC_PRICE_OFFLINE_ASSETS = '+JSON.stringify(assets)+';\n');
console.log(JSON.stringify({version:VERSION,sourceCommit:assets.sourceCommit,templateSha256:assets.templateSha256,templateBytes:Buffer.byteLength(template)}));
